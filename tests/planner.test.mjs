test('SprintEngine pr review detects issues', async () => {
  const root = makeFixture('pr');
  const engine = new SprintEngine(root);

  const diff = `diff --git a/src/auth.ts b/src/auth.ts
+function login() {
+  console.log("logging in");
+  const apiKey = "sk-123456";
+  debugger;
+  return true;
+}`;

  const result = await engine.reviewPR('feature/login', diff);
  assert.equal(result.summary.issuesFound, 3);
  assert.ok(result.comments.some((c) => c.rule === 'errorHandling'));
  assert.ok(result.comments.some((c) => c.rule === 'hardcodedSecrets'));
  assert.ok(result.comments.some((c) => c.rule === 'debugLeftovers'));
});

