test('SprintEngine autoPrioritize ranks items by priority and dependencies', async () => {
  const root = makeFixture('prioritize');
  const engine = new SprintEngine(root);

  const item1 = await engine.createItem({ type: 'task', title: 'P0 task', priority: 'P0' });
  const _item2 = await engine.createItem({ type: 'story', title: 'P2 story', priority: 'P2' });
  const item3 = await engine.createItem({
    type: 'task',
    title: 'Dependent task',
    priority: 'P2',
    dependencies: [item1.id],
  });

  const prioritized = await engine.autoPrioritize({});
  assert.equal(prioritized.length, 3);
  assert.ok(prioritized[0].priorityScore > prioritized[1].priorityScore);
  // item1 (P0) should rank highest
  assert.equal(prioritized[0].id, item1.id);
  // item3 depends on item1, so should get a dependency bonus
  const item3Result = prioritized.find((p) => p.id === item3.id);
  assert.ok(item3Result.priorityScore > 0);
});

